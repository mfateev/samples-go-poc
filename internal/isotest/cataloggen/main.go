// Command cataloggen records native entry packages used by the sample suites.
package main

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	root, err := os.Getwd()
	must(err)
	mod, err := os.ReadFile(filepath.Join(root, "go.mod"))
	must(err)
	module := strings.Fields(string(mod))[1]
	packages := make(map[string]bool)
	must(filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			if strings.HasPrefix(entry.Name(), ".") || entry.Name() == "testdata" || entry.Name() == "bin" {
				return fs.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		source, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.ParseComments)
		if err != nil {
			return err
		}
		if source.Name.Name == "main" {
			return nil
		}
		for _, decl := range source.Decls {
			function, ok := decl.(*ast.FuncDecl)
			if !ok || function.Doc == nil {
				continue
			}
			for _, comment := range function.Doc.List {
				if comment.Text != "//go:isolate" {
					continue
				}
				relative, err := filepath.Rel(root, filepath.Dir(path))
				if err != nil {
					return err
				}
				packages[module+"/"+filepath.ToSlash(relative)] = true
			}
		}
		return nil
	}))
	paths := make([]string, 0, len(packages))
	for path := range packages {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	var source strings.Builder
	// The driver reads this import block as source; keep the package line first.
	source.WriteString("package isotest\n\n// Code generated by internal/isotest/cataloggen; DO NOT EDIT.\nimport (\n")
	for _, path := range paths {
		fmt.Fprintf(&source, "_ %q\n", path)
	}
	source.WriteString(")\n")
	formatted, err := format.Source([]byte(source.String()))
	must(err)
	must(os.WriteFile(filepath.Join(root, "internal/isotest/testdata/catalog.txt"), formatted, 0644))
	fmt.Printf("Recorded %d native entry packages\n", len(paths))
}
func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
